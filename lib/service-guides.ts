export function getServiceGuide(slug: string): ServiceGuide | undefined {
  return SERVICE_GUIDES.find((guide) => guide.slug === slug)
}

/** 목록·링크에 쓰는 이름: "입주청소 견적 안내", "보일러 견적 안내" */
export function guideLinkLabel(guide: ServiceGuide): string {
  return `${guide.navLabel} 견적 안내`
}

/** 설비 → 청소 순으로 묶은 안내 목록 (안내 목록·홈에서 사용) */
export const GUIDE_GROUPS: { kind: ServiceGuide['kind']; title: string; guides: ServiceGuide[] }[] = [
  { kind: '설비', title: '집수리·설비', guides: SERVICE_GUIDES.filter((g) => g.kind === '설비') },
  { kind: '청소', title: '청소', guides: SERVICE_GUIDES.filter((g) => g.kind === '청소') },
]

/** 견적 요청 폼 링크 (대분류와 세부 공종을 미리 골라 둡니다) */
export function guideRequestHref(guide: ServiceGuide): string {
  const params = new URLSearchParams({ category: guide.category })
  if (guide.subcategory) params.set('sub', guide.subcategory)
  return `/requests?${params.toString()}`
}
